"""Writes firmware/xiao_sense/count_model.h: the count model zlib-compressed, as a C string literal (raw bytes in flash)."""
import sys
import zlib

src, dst = sys.argv[1], sys.argv[2]
raw = open(src, "rb").read()
z = zlib.compress(raw, 9)
out, line, prev_octal = [], [], False
for b in z:
    c = chr(b)
    if 32 <= b < 127 and c not in r'"\?':
        if prev_octal and c in "01234567":
            tok = r"\%03o" % b         # a digit right after an octal escape would be read as part of it
        else:
            tok = c
        prev_octal = tok != c
    else:
        tok = r"\%03o" % b
        prev_octal = True
    line.append(tok)
    if sum(map(len, line)) >= 160:
        out.append('"' + "".join(line) + '"')
        line, prev_octal = [], False
if line:
    out.append('"' + "".join(line) + '"')
with open(dst, "w", newline="\n") as f:
    f.write("// Seeed Swift-YOLO Nano person detector (models/swift_yolo_nano_person_192_int8.tflite, SSCMA model zoo),\n")
    f.write("// zlib-compressed so firmware + model fit the 3 MB app flash; unpacked into PSRAM at startup.\n")
    f.write("// Generated by tools/make_count_header.py, don't edit.\n#pragma once\n")
    f.write(f"const unsigned int COUNT_MODEL_BYTES = {len(raw)};\n")
    f.write(f"const unsigned int COUNT_MODEL_Z_BYTES = {len(z)};\n")
    f.write("const unsigned char g_count_model_z[] =\n" + "\n".join(out) + ";\n")
print(len(raw), len(z), sum(len(l) + 1 for l in out))

"""Writes firmware/xiao_sense/count_model_1.h and count_model_2.h: the people-count model zlib-compressed, as C string
literals (raw bytes in flash), split in two because Velxio won't build a file over 4 million characters.
Usage: python tools/make_count_header.py models/swift_yolo_nano_person_192_int8.tflite firmware/xiao_sense
"""
import sys
import zlib


def c_literal(data: bytes) -> str:
    out, line, prev_octal = [], [], False
    for b in data:
        c = chr(b)
        if 32 <= b < 127 and c not in r'"\?':
            # a digit right after an octal escape would be read as part of it
            tok = r"\%03o" % b if prev_octal and c in "01234567" else c
            prev_octal = tok != c
        else:
            tok = r"\%03o" % b
            prev_octal = True
        line.append(tok)
        if sum(map(len, line)) >= 160:
            out.append('"' + "".join(line) + '"')
            line, prev_octal = [], False
    if line:
        out.append('"' + "".join(line) + '"')
    return "\n".join(out)


src, folder = sys.argv[1], sys.argv[2]
raw = open(src, "rb").read()
z = zlib.compress(raw, 9)
half = len(z) // 2
for part, chunk in ((1, z[:half]), (2, z[half:])):
    with open(f"{folder}/count_model_{part}.h", "w", newline="\n") as f:
        f.write(f"// People-count model, part {part} of 2: Seeed Swift-YOLO Nano person detector\n")
        f.write("// (models/swift_yolo_nano_person_192_int8.tflite, SSCMA model zoo), zlib-compressed so firmware + model fit\n")
        f.write("// the 3 MB app flash; unpacked into PSRAM at startup. Generated by tools/make_count_header.py, don't edit.\n")
        f.write("#pragma once\n")
        if part == 1:
            f.write(f"const unsigned int COUNT_MODEL_BYTES = {len(raw)};\n")
        f.write(f"const unsigned int COUNT_MODEL_Z{part}_BYTES = {len(chunk)};\n")
        f.write(f"const unsigned char g_count_model_z{part}[] =\n{c_literal(chunk)};\n")
print(len(raw), len(z))

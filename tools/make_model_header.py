"""Writes a .tflite model as a zlib-compressed C string literal header (raw bytes in flash, unpacked into PSRAM by the
sketch with the ESP32-S3 ROM decompressor). Compression keeps firmware + models inside Velxio's 3 MB app partition.
Usage: python tools/make_model_header.py models/face96_int8.tflite firmware/xiao_sense/face_model.h face_model
"""
import sys
import zlib

VELXIO_MAX_CHARS = 4_000_000   # Velxio refuses to build bigger files


def c_literal(data: bytes) -> str:
    out, line, prev_octal = [], [], False
    for b in data:
        c = chr(b)
        if 32 <= b < 127 and c not in r'"\?':
            # a digit right after an octal escape would be read as part of it
            tok = r"\%03o" % b if prev_octal and c in "01234567" else c
            prev_octal = tok != c
        else:
            tok = r"\%03o" % b
            prev_octal = True
        line.append(tok)
        if sum(map(len, line)) >= 160:
            out.append('"' + "".join(line) + '"')
            line, prev_octal = [], False
    if line:
        out.append('"' + "".join(line) + '"')
    return "\n".join(out)


src, dst, name = sys.argv[1], sys.argv[2], sys.argv[3]
raw = open(src, "rb").read()
z = zlib.compress(raw, 9)
text = (f"// {src.replace(chr(92), '/')}, zlib-compressed; unpacked into PSRAM at startup.\n"
        "// Generated by tools/make_model_header.py, don't edit.\n#pragma once\n"
        f"const unsigned int {name.upper()}_BYTES = {len(raw)};\n"
        f"const unsigned int {name.upper()}_Z_BYTES = {len(z)};\n"
        f"const unsigned char g_{name}_z[] =\n{c_literal(z)};\n")
assert len(text) < VELXIO_MAX_CHARS, f"{len(text)} characters: too big for Velxio, split the model"
open(dst, "w", newline="\n").write(text)
print(f"{dst}: {len(raw)} bytes -> {len(z)} compressed, {len(text)} characters")
